"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const source = fs.readFileSync(path.join(__dirname, "..", "index.js"), "utf8");
assert.match(source, /bot\.action\(\/\^panel:\(home\|chemical\|prices\|lists\|merchants\|deals\|weather\|reports\|health\|diagnostics\|settings\|groups/);
assert.match(source, /cmd === "panel" && m\.chatType === "private"/);
assert.match(source, /const adminPanel = require\("\.\/modules\/admin-panel"\)/);
assert.match(source, /const serviceSettings = require\("\.\/core\/service-settings"\)/);
assert.match(source, /section === "home" \? adminPanel\.privatePanelKeyboard\(\) : adminPanel\.actionKeyboard\(\)/, "returning to the home panel must restore the service buttons");
assert.match(source, /SELECT COUNT\(\*\)::int AS count FROM merchants/);
assert.match(source, /cmd === "settings"/);
assert.ok(source.includes("bot.action(/^group-settings:(refresh|close|toggle:[a-z]+)$/"), "group settings must register the close callback");
assert.ok(source.includes('if (action === "close")') && source.includes("await ctx.editMessageReplyMarkup({ inline_keyboard: [] });"), "group settings back must close the keyboard and return to the conversation");
assert.doesNotMatch(source, /panel:(protection|inactive)|cmd === "admin"|cmd === "antispam"|cmd === "schedule"|cmd === "warn"|cmd === "warnings"|cmd === "clearwarn"|cmd === "inactive"/);
assert.doesNotMatch(source, /moderation_settings|moderation_events|PROTECTION_ENFORCE|recordActivity/);
assert.match(source, /if \(cmd === "قائمة" \|\| cmd === "pricelist"\)/);
assert.match(source, /if \(cmd === "weather" \|\| cmd === "الطقس"\)/);
assert.match(source, /if \(isChemicalCommand\)/);
assert.match(source, /isAuthorizedChat\(m\.chatId\)/);
const settingsStart=source.indexOf('if (cmd === "settings" && ["private", "group", "supergroup"].includes(m.chatType))');
const approvedGate=source.indexOf('if (m.chatType !== "private" && !(await isAuthorizedChat(m.chatId))) return;',settingsStart);
assert.ok(settingsStart>=0 && approvedGate>settingsStart);
const handler=source.slice(settingsStart,approvedGate);
assert.ok(handler.includes('isMaster(m.userId)'),"private global settings must be bot-master-only");
assert.ok(handler.includes('listOwnedGroups(db.pool, m.userId)'),"group owners can select their own groups in private");
assert.ok(handler.includes('canManage(ctx.telegram, m.chatId, m.userId)'),"group settings must verify the group creator");
assert.match(source,/bot\.action\(\/\^prv:\(approve\|new\|ignore\):\(\\d\+\)\$\/, async ctx => \{\s*\/\/ Stop Telegram's callback spinner before database and administrator API checks\.\s*await ctx\.answerCbQuery\(/);
assert.match(source,/bot\.action\(\/\^prv:edit:\(\\d\+\)\$\/, async ctx => \{\s*\/\/ Acknowledge immediately so Telegram does not leave the button spinning while access is checked\.\s*await ctx\.answerCbQuery\(/);
console.log("Borsa runtime surface and settings authorization test: OK");
