"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const ai = fs.readFileSync(path.join(__dirname, "../core/ai.js"), "utf8");
const index = fs.readFileSync(path.join(__dirname, "../index.js"), "utf8");
assert.match(ai, /gemini-3\\.5-flash-lite/);
assert.match(ai, /x-goog-api-key/);
assert.doesNotMatch(ai.match(/function openAIProvider[\\s\\S]*?function xaiProvider/)[0], /temperature:/, "Responses request must not send unsupported temperature field");
assert.match(ai, /AI_FALLBACK_ENABLED === "true"/);
assert.match(ai, /function isCredentialError/);
assert.match(ai, /fallbackProviders\.flatMap/);
assert.match(ai, /if \(!retryable && !credentialError\)/);
assert.match(index, /createAI\(\{ provider: "gemini", fallbackProviders: \["openai", "xai"\] \}\)/);
console.log("AI provider routing and chemical fallback tests: OK");
