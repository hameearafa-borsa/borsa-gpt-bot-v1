"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const ai = fs.readFileSync(path.join(__dirname, "../core/ai.js"), "utf8");
assert.match(ai, /gemini-3\.8-flash/);
assert.match(ai, /gemini-3\.6-flash/);
assert.match(ai, /gemini-3\.5-flash/);
assert.match(ai, /x-goog-api-key/);
assert.doesNotMatch(ai.match(/function openAIProvider[\s\S]*?function xaiProvider/)[0], /temperature:/, "Responses request must not send unsupported temperature field");
assert.doesNotMatch(ai.match(/function geminiProvider[\s\S]*?function providersFromEnv/)[0], /temperature/, "Gemini 3 rejects temperature");
assert.match(ai, /AI_FALLBACK_ENABLED === "true"/);
assert.match(ai, /if \(!isRetryable\(e\)\) throw e/);
console.log("AI provider routing tests: OK");
