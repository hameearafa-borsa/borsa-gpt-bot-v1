"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const ai = fs.readFileSync(path.join(__dirname, "../core/ai.js"), "utf8");
const index = fs.readFileSync(path.join(__dirname, "../index.js"), "utf8");
assert.ok(ai.includes("gemini-3.5-flash-lite"));
assert.ok(ai.includes("x-goog-api-key"));
const openAISection = ai.slice(ai.indexOf("function openAIProvider"), ai.indexOf("function xaiProvider"));
assert.ok(openAISection.length > 0, "OpenAI provider implementation should exist");
assert.ok(!openAISection.includes("temperature:"), "Responses request must not send unsupported temperature field");
assert.ok(ai.includes('AI_FALLBACK_ENABLED === "true"'));
assert.ok(ai.includes("function isCredentialError"));
assert.ok(ai.includes("fallbackProviders.flatMap"));
assert.ok(ai.includes("if (!retryable && !credentialError)"));
assert.ok(index.includes('createAI({ provider: "gemini", fallbackProviders: ["openai", "xai"] })'));
console.log("AI provider routing and chemical fallback tests: OK");
