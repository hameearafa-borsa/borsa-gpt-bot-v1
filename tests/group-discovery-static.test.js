assert.match(source, /\[GROUP_CLAIM_RECEIVED\]/, "group claim dispatch must be traceable");
assert.match(source, /\[GROUP_APPROVAL_OWNER_NOTIFIED\]/, "new group additions must notify the bot owner");
assert.match(source, /\[GROUP_APPROVAL_OWNER_NOTIFY_FAILED\]/, "failed owner notifications must be visible in runtime logs");
assert.match(source, /!\["group", "supergroup"\]\.includes\(pending\.rows\[0\]\.chat_type\)/, "approval command must reject non-group pending records");
