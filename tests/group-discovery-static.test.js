"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const source = fs.readFileSync(require.resolve("../index.js"), "utf8");
assert.match(source, /"my_chat_member"/);
assert.match(source, /!\["group", "supergroup"\]\.includes\(chat\.type\)/, "group approval handler must ignore channels");
assert.match(source, /"chat_member"/);
assert.match(source, /group_approval_required/, "new groups must enter the pending approval flow");
assert.match(source, /await bot\.telegram\.setWebhook\(webhookConfig\.url,\s*\{/);
assert.match(source, /createWebhookServer\(bot, webhookConfig\)/);
assert.doesNotMatch(source, /await bot\.launch\(/);
assert.match(source, /cmd === "claim" && \["group", "supergroup"\]/);
assert.match(source, /if \(await isAuthorizedChat\(m\.chatId\)\) \{[\s\S]*?هذه المجموعة معتمدة بالفعل/);
assert.match(source, /cmd === "approvechat" && m\.chatType === "private"/);
assert.match(source, /!\["group", "supergroup"\]\.includes\(pending\.rows\[0\]\.chat_type\)/, "approval command must reject non-group pending records");
assert.match(source, /pending_group_approvals/);
const memberHandler = source.match(/bot\.on\("my_chat_member",[\s\S]*?\n\}\);/);
assert.ok(memberHandler, "group membership handler must exist");
assert.match(memberHandler[0], /SELECT active FROM authorized_chats WHERE chat_id=\$1/);
assert.match(memberHandler[0], /existing\.rows\[0\]\?\.active === true/);
assert.match(memberHandler[0], /authorized_group_bot_readded/);
assert.match(memberHandler[0], /UPDATE authorized_chats SET active=FALSE WHERE chat_id=\$1/);
assert.match(memberHandler[0], /group_approval_required/);
assert.match(memberHandler[0], /status='pending'/);
assert.doesNotMatch(memberHandler[0], /authorizeChat\(/, "adding the bot must never authorize a new group automatically");
assert.doesNotMatch(memberHandler[0], /status='approved'/, "adding the bot must never mark a pending group approved");
assert.match(source, /Number\(m\.userId\) !== MASTER_ID/, "approval command must remain restricted to the fixed master");
assert.match(source, /await approvePendingGroup\(\{[\s\S]*?approvedBy: m\.userId/, "approval flow must invoke transactional helper");
const menuBlock = source.match(/await bot\.telegram\.setMyCommands\(\[([\s\S]*?)\], \{ scope: \{ type: "all_group_chats" \} \}\)/);
assert.ok(menuBlock, "service command menu must be declared");
assert.match(menuBlock[1], /command: "chemical"/);
assert.match(menuBlock[1], /command: "weather"/);
assert.doesNotMatch(menuBlock[1], /approvechat|claim|settings|antispam|schedule|warn|pricelist|inactive/);
assert.match(source, /cmd === "قائمة" \|\| cmd === "pricelist"/);
console.log("GROUP ACCESS CONTROL + SERVICE MENU STATIC TESTS: OK");
